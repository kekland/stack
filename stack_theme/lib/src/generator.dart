List<String> _generateTypography(ThemeDescription description) {
  final lines = <String>[];

  lines.add(_baseTextStyleTemplate);

  for (final style in description.typography) {
    final className = '${_capitalize(style.name)}TextStyle';
    final baseClassName = '${className}Base';

    lines.add('class $baseClassName extends BaseTextStyle {');
    lines.add('  $baseClassName(');
    lines.add('    super.base, {');
    for (final color in style.colors) lines.add('    required this.${color.name},');
    lines.add('    super.package,');
    lines.add('  });');
    lines.add('');

    lines.add('  factory $baseClassName.generate(TextStyle base, AppColors colors) {');
    lines.add('    return $baseClassName(');
    lines.add('      base,');
    for (final color in style.colors) lines.add('      ${color.name}: base.copyWith(color: colors.${color.getter}),');
    lines.add('    );');
    lines.add('  }');

    if (style.colors.isNotEmpty) lines.add('');
    for (final color in style.colors) lines.add('  final TextStyle ${color.name};');

    lines.add('}');
    lines.add('');

    lines.add('class $className extends $baseClassName {');
    lines.add('  $className(');
    lines.add('    super.base, {');
    for (final color in style.colors) lines.add('    required super.${color.name},');
    for (final weight in style.weights) lines.add('    required this.${weight.name},');
    lines.add('    super.package,');
    lines.add('  });');

    final variants = style.weights.isNotEmpty ? style.weights.map((w) => w.name) : ['base'];
    final defaultVariant = variants.first;

    lines.add('');
    lines.add('  factory $className.generate({');
    for (final variant in variants) lines.add('    required TextStyle $variant,');
    lines.add('    required AppColors colors,');
    lines.add('  }) {');
    lines.add('    return $className(');
    lines.add('      $defaultVariant,');
    for (final color in style.colors)
      lines.add('      ${color.name}: $defaultVariant.copyWith(color: colors.${color.getter}),');
    for (final weight in style.weights)
      lines.add('      ${weight.name}: $baseClassName.generate(${weight.name}, colors),');
    lines.add('    );');
    lines.add('  }');

    if (style.weights.isNotEmpty) lines.add('');
    for (final weight in style.weights) lines.add('  final $baseClassName ${weight.name};');
    lines.add('}');
    lines.add('');
  }

  lines.add('typedef AppTypography = ({');
  for (final style in description.typography) {
    final className = '${_capitalize(style.name)}TextStyle';
    lines.add('  $className ${style.name},');
  }

  lines.add('});');
  lines.add('');
  lines.add('class AppTypographyGenerator {');
  lines.add('  static AppTypography generate(');
  lines.add('    AppColors colors, {');
  for (final style in description.typography) {
    if (style.weights.isEmpty) {
      lines.add('    required TextStyle ${style.name},');
    } else {
      for (final weight in style.weights) {
        lines.add('    required TextStyle ${style.name}${_capitalize(weight.name)},');
      }
    }
  }
  lines.add('    TextStyle? overrides,');
  lines.add('  }) {');
  lines.add('    return (');
  for (final style in description.typography) {
    final className = '${_capitalize(style.name)}TextStyle';
    if (style.weights.isEmpty) {
      lines.add('      ${style.name}: $className.generate(base: ${style.name}.merge(overrides), colors: colors),');
    } else {
      lines.add('      ${style.name}: $className.generate(');
      for (final weight in style.weights) {
        lines.add('        ${weight.name}: ${style.name}${_capitalize(weight.name)}.merge(overrides),');
      }
      lines.add('        colors: colors,');
      lines.add('      ),');
    }
  }
  lines.add('    );');
  lines.add('  }');
  lines.add('}');
  lines.add('');

  if (lines.isNotEmpty) lines.removeLast();
  return lines;
}

List<String> _generateColors(ThemeDescription description) {
  final typedefs = <String>[];
  final lines = <String>[];

  String _generateFor(ColorDescription color) {
    String type;

    if (color is LeafColorDescription) {
      type = 'Color';
    } else if (color is SurfaceColorDescription) {
      type = 'SurfaceColor';
    } else if (color is ActionableColorDescription) {
      type = 'ActionableColor';
    } else if (color is GroupColorDescription) {
      final typedefName = '${_capitalize(color.name)}Colors';

      typedefs.add('typedef $typedefName = ({');
      for (final child in color.children) {
        final childLine = _generateFor(child);
        typedefs.add('  $childLine,');
      }
      typedefs.add('});');
      typedefs.add('');

      type = typedefName;
    } else {
      throw Exception('Unknown ColorDescription type: ${color.runtimeType}');
    }

    type = color.isOptional ? '$type?' : type;
    final line = '$type ${color.name}';

    return line;
  }

  lines.add('typedef AppColors = ({');
  for (final color in description.colors) {
    final line = _generateFor(color);
    lines.add('  $line,');
  }

  lines.add('});');
  return [...typedefs, ...lines];
}

List<String> _generateShadows(ThemeDescription description) {
  final lines = <String>[];

  if (description.shadows.isEmpty) return lines;

  lines.add('typedef AppShadows = ({');
  for (final shadow in description.shadows) lines.add('  List<BoxShadow> ${shadow.name},');
  lines.add('});');

  return lines;
}

