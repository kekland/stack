import 'package:stack_theme/stack_theme.dart';

List<String> generateThemeFromDescription(ThemeDescription description) {
  final lines = <String>[];

  lines.add('// GENERATED CODE - DO NOT MODIFY BY HAND');
  lines.add('// Generated by stack_theme. Please refer to the documentation for more information.');
  lines.add('');
  lines.add('import \'package:flutter/widgets.dart\';');
  lines.add('import \'package:stack_ui/stack_ui.dart\';');
  lines.add('');

  final blocks = <List<String>>[];

  blocks.add(_generateFinal(description));
  blocks.add(_generatePlatformEnum(description));
  blocks.add(_generateVariantEnum(description));
  blocks.add(_generateColors(description));
  blocks.add(_generateTypography(description));
  blocks.add(_generateShadows(description));
  blocks.add(_generateAnimations(description));
  blocks.add(_generateSizes(description));

  // Finalize lines by adding blocks
  final nonEmptyBlocks = blocks.where((block) => block.isNotEmpty).toList();
  for (var i = 0; i < nonEmptyBlocks.length; i++) {
    lines.addAll(nonEmptyBlocks[i]);
    if (i != nonEmptyBlocks.length - 1) lines.add('');
  }

  return lines;
}

String _capitalize(String input) => input.isEmpty ? input : '${input[0].toUpperCase()}${input.substring(1)}';

List<String> _generatePlatformEnum(ThemeDescription description) {
  final lines = <String>[];

  if (description.platforms.isEmpty) return lines;

  lines.add('enum ThemePlatform {');
  for (final platform in description.platforms) lines.add('  $platform,');
  lines.add('}');

  return lines;
}

List<String> _generateVariantEnum(ThemeDescription description) {
  final lines = <String>[];

  if (description.variants.isEmpty) return lines;

  lines.add('enum ThemeVariant {');
  for (final variant in description.variants) lines.add('  $variant,');
  lines.add('}');

  return lines;
}

