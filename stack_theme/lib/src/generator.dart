List<String> _generateFinal(ThemeDescription description) {
  final lines = <String>[];

  lines.add('typedef AppTheme = ({');
  lines.add('  Brightness brightness,');
  if (description.platforms.isNotEmpty) lines.add('  ThemePlatform platform,');
  if (description.variants.isNotEmpty) lines.add('  ThemeVariant variant,');
  if (description.colors.isNotEmpty) lines.add('  AppColors colors,');
  if (description.typography.isNotEmpty) lines.add('  AppTypography typography,');
  if (description.shadows.isNotEmpty) lines.add('  AppShadows shadows,');
  if (description.animations.isNotEmpty) lines.add('  AppAnimations animations,');
  if (description.sizes.isNotEmpty) lines.add('  AppSizes sizes,');
  lines.add('});');
  lines.add('');
  lines.add('class _InheritedAppTheme extends InheritedWidget {');
  lines.add('  const _InheritedAppTheme({');
  lines.add('    required this.theme,');
  lines.add('    required super.child,');
  lines.add('  });');
  lines.add('');
  lines.add(
    '  static AppTheme of(BuildContext context) => context.dependOnInheritedWidgetOfExactType<_InheritedAppTheme>()!.theme;',
  );
  lines.add('');
  lines.add('  final AppTheme theme;');
  lines.add('');
  lines.add('  @override');
  lines.add('  bool updateShouldNotify(covariant _InheritedAppTheme oldWidget) => theme != oldWidget.theme;');
  lines.add('}');
  lines.add('');
  lines.add('class InheritedAppTheme extends StatelessWidget {');
  lines.add('  const InheritedAppTheme({');
  lines.add('    super.key,');
  lines.add('    required this.theme,');
  lines.add('    required this.child,');
  lines.add('  });');
  lines.add('');
  lines.add('  final AppTheme theme;');
  lines.add('  final Widget child;');
  lines.add('');
  lines.add('  @override');
  lines.add('  Widget build(BuildContext context) {');
  lines.add('    return InheritedBrightness(');
  lines.add('      brightness: theme.brightness,');
  lines.add('      child: _InheritedAppTheme(theme: theme, child: child),');
  lines.add('    );');
  lines.add('  }');
  lines.add('}');
  lines.add('');
  lines.add('extension AppThemeContext on BuildContext {');
  lines.add('  AppTheme get theme => _InheritedAppTheme.of(this);');
  if (description.platforms.isNotEmpty) lines.add('  ThemePlatform get themePlatform => theme.platform;');
  if (description.variants.isNotEmpty) lines.add('  ThemeVariant get themeVariant => theme.variant;');
  if (description.colors.isNotEmpty) lines.add('  AppColors get colors => theme.colors;');
  if (description.typography.isNotEmpty) lines.add('  AppTypography get typography => theme.typography;');
  if (description.shadows.isNotEmpty) lines.add('  AppShadows get shadows => theme.shadows;');
  if (description.animations.isNotEmpty) lines.add('  AppAnimations get animations => theme.animations;');
  if (description.sizes.isNotEmpty) lines.add('  AppSizes get sizes => theme.sizes;');
  lines.add('}');
  lines.add('');
  if (description.variants.isNotEmpty) {
    lines.add('class VariantBuilder extends StatelessWidget {');
    lines.add('  const VariantBuilder({');
    lines.add('    super.key,');
    for (final variant in description.variants) lines.add('    required this.$variant,');
    lines.add('  });');
    lines.add('');
    for (final variant in description.variants) lines.add('  final WidgetBuilder $variant;');
    lines.add('');
    lines.add('  @override');
    lines.add('  Widget build(BuildContext context) {');
    lines.add('    final variant = context.themeVariant;');
    lines.add('    return switch(variant) {');
    for (final variant in description.variants) lines.add('      .$variant => $variant(context),');
    lines.add('    };');
    lines.add('  }');
    lines.add('}');
  }

  return lines;
}
